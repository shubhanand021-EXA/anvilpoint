import type { Ecosystem } from '../../types.js';

export interface CiOptions {
  ecosystem: Ecosystem;
  runs: string[];
  os: string;
  scheduleWeekly: boolean;
}

export const CI_STEPS: Record<Ecosystem, { id: string; label: string; commands: string[] }[]> = {
  node: [
    { id: 'install', label: 'Install dependencies', commands: ['npm ci'] },
    { id: 'test', label: 'Run tests', commands: ['npm test -- --runInBand'] },
    { id: 'lint', label: 'Lint (if configured)', commands: ['npm run lint --if-present'] },
    { id: 'build', label: 'Build (if configured)', commands: ['npm run build --if-present'] },
  ],
  python: [
    { id: 'install', label: 'Install dependencies', commands: ['pip install -r requirements.txt'] },
    { id: 'test', label: 'Run tests', commands: ['pytest'] },
    { id: 'lint', label: 'Lint with Ruff (if configured)', commands: ['ruff check .'] },
    { id: 'build', label: 'Build package', commands: ['python -m build'] },
  ],
  rust: [
    { id: 'install', label: 'Fetch dependencies', commands: ['cargo fetch'] },
    { id: 'test', label: 'Run tests', commands: ['cargo test --all-features'] },
    { id: 'lint', label: 'Clippy', commands: ['cargo clippy -- -D warnings'] },
    { id: 'build', label: 'Build', commands: ['cargo build --verbose'] },
  ],
  go: [
    { id: 'install', label: 'Download modules', commands: ['go mod download'] },
    { id: 'test', label: 'Run tests', commands: ['go test ./...'] },
    { id: 'lint', label: 'Vet', commands: ['go vet ./...'] },
    { id: 'build', label: 'Build', commands: ['go build ./...'] },
  ],
};

const RUNTIME_SETUP: Record<Ecosystem, string> = {
  node: '      - uses: actions/setup-node@v4\n        with:\n          node-version: "20"\n          cache: npm',
  python: '      - uses: actions/setup-python@v5\n        with:\n          python-version: "3.12"',
  rust: '      - uses: dtolnay/rust-toolchain@stable\n',
  go: '      - uses: actions/setup-go@v5\n        with:\n          go-version: "1.22"',
};

const RUNTIME_VERSION_NOTE: Record<Ecosystem, string> = {
  node: 'Pinned to Node 20 (actions/setup-node@v4). Adjust to engines in package.json.',
  python: 'Pinned to Python 3.12 (actions/setup-python@v5). Adjust to requires-python.',
  rust: 'Uses stable toolchain (dtolnay/rust-toolchain@stable).',
  go: 'Pinned to Go 1.22 (actions/setup-go@v5). Adjust to go.mod directive.',
};

/** Generate a reviewable GitHub Actions workflow. Never executed; user must verify. */
export function renderCiWorkflow(opts: CiOptions): { yaml: string; notes: string[] } {
  const steps = (CI_STEPS[opts.ecosystem] ?? []).filter((s) => opts.runs.includes(s.id));
  const notes = [
    RUNTIME_VERSION_NOTE[opts.ecosystem],
    'Workflow uses minimal permissions (contents: read).',
    'Commands are templates inferred from ecosystem conventions — verify each command exists in your repo before enabling.',
    'Running this on GitHub is subject to GitHub Actions usage limits; FORGEKIT does not execute it.',
  ];
  const runSteps = steps
    .map((s) => `      - name: ${s.label}\n        run: ${s.commands.join(' && ')}`)
    .join('\n');
  const schedule = opts.scheduleWeekly ? '\n  schedule:\n    - cron: "0 6 * * 1"' : '';
  const yaml =
    `# Generated by FORGEKIT — review before committing. Not executed by FORGEKIT.\n` +
    `name: CI\n\n` +
    `on:\n  push:\n    branches: [main]\n  pull_request:${schedule ? '' : ''}\n${schedule}\n\n` +
    `permissions:\n  contents: read\n\n` +
    `jobs:\n  build:\n    runs-on: ${opts.os}\n    steps:\n` +
    `      - uses: actions/checkout@v4\n${RUNTIME_SETUP[opts.ecosystem]}\n${runSteps}\n`;
  return { yaml, notes };
}
